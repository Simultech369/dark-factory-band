class SoftwareFactory:
    """Dark Factory core engine."""

    def __init__(self, workspace_dir: str):
        self.workspace_dir = Path(workspace_dir).resolve()
        self.guardrails = CouncilGuardrails(str(self.workspace_dir))
        self.run_log: list[dict[str, str]] = []
        self.generated_files: list[str] = []
        self.surface_results: list[ReviewResult] = []
        self.plan_data: dict[str, Any] = {}

    def log_step(self, phase: str, message: str, status: str = "INFO") -> None:
        entry = {
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
            "phase": phase,
            "message": message,
            "status": status,
        }
        self.run_log.append(entry)
        print(f"[{entry['timestamp']}] [{phase}] [{status}] {message}", flush=True)

    def plan(self, product_name: str, specification: str) -> dict[str, Any]:
        """Surface 1: validate spec and produce a concrete architecture plan."""
        self.log_step("PLANNING", f"Decomposing specification for '{product_name}'...")
        spec_check = self.guardrails.review_surface_1_spec(product_name, specification)
        self.surface_results.append(spec_check)
        self.log_step(
            "SURFACE_1_SPEC",
            spec_check.details,
            "SUCCESS" if spec_check.passed else "FAILURE",
        )
        if not spec_check.passed:
            raise ValueError(spec_check.details)

        self.plan_data = {
            "product": product_name,
            "architecture": "thread-safe in-memory payment ledger",
            "modules": [
                {"name": "pocketful.payments", "description": "balances, transfer, split rounding"},
                {"name": "tests.test_payments", "description": "money conservation and concurrency"},
                {"name": "README", "description": "demo and verification commands"},
            ],
            "acceptance_criteria": [
                "deterministic cent rounding",
                "failed split payments do not partially mutate balances",
                "idempotency keys prevent duplicate retry transfers",
                "no negative balances",
                "concurrent transfers conserve total money",
                "ruff and pytest pass from the generated workspace",
            ],
        }
        self.log_step("PLANNING", "Architecture plan established with executable checks.", "SUCCESS")
        return self.plan_data

    def _write_file(self, relative_path: str, content: str) -> None:
        path = self.workspace_dir / relative_path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(textwrap.dedent(content).lstrip(), encoding="utf-8", newline="\n")
        self.generated_files.append(relative_path.replace("\\", "/"))

