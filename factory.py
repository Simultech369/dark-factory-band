"""Dark Factory: autonomous, receipt-backed software factory demo.

This package targets the Dark Factory hackathon with a narrow but real loop:
plan a clean-room Pocketful payment engine, generate working Python files, run
ruff and pytest, scan generated artifacts, and export a receipt tied to hashes
and tool exit codes.
"""

